"""
Text helpers shared by the generators, so that every generated file is byte-identical run to run.

Numbers are printed with a fixed number of decimals, never with ``repr()`` or ``str()``. Those
print the shortest text that reads back as the same float, so 0.1 + 0.2 prints as
0.30000000000000004 and a value computed in another order could change the file. Rounded to a
fixed precision both print 0.3. Layout values have millimetre precision, so 6 decimals in YAML
(and 4 in SDF, see world.py) lose nothing.

The YAML files are written as text rather than with ``yaml.safe_dump``: the text is then fixed
by this code, not by the PyYAML version, and it can carry comments that explain the file.
"""

import re

import yaml

COMMAND = 'ros2 run warehouse_layout generate'

# A string written without quotes must look like a name. yaml_str() also checks that YAML
# reads it back as the same string (not as a number, a boolean or null).
_PLAIN = re.compile(r'^[A-Za-z0-9_][A-Za-z0-9_\-]*$')


def notice(check=True):
    """
    Return the do-not-edit notice that every generated file starts with, as lines of text.

    ``check=False`` leaves out the line about ``--check``: an XML comment may not contain two
    hyphens in a row.
    """
    lines = [
        'Generated from warehouse_layout/config/layout.yaml (and the robot size in',
        'warehouse_description/config/robot.yaml). Do not edit this file: edit layout.yaml,',
        'then run from the workspace root:',
        f'  {COMMAND}',
    ]
    if check:
        lines.append(f'`{COMMAND} --check` exits with 1 while this file is out of date.')
    return lines


def count(number, noun):
    """Return a count with its noun, for summaries: '1 drop', '3 docks'."""
    return f'{number} {noun}' if number == 1 else f'{number} {noun}s'


def yaml_comment(lines):
    """Return lines of text as YAML comment lines ('# text', or '#' for an empty line)."""
    return [f'# {line}' if line else '#' for line in lines]


def yaml_float(value):
    """Return a number as a YAML float: at most 6 decimals, always with a decimal point."""
    text = f'{value:.6f}'.rstrip('0')
    if text.endswith('.'):
        text += '0'
    # A tiny negative value rounds to -0.0; write it as 0.0 so the sign cannot flip the file.
    return '0.0' if text == '-0.0' else text


def yaml_str(value):
    """Return a string for YAML: plain if YAML reads it back unchanged, else single-quoted."""
    if _PLAIN.match(value) and yaml.safe_load(value) == value:
        return value
    # For example '1' (an aisle ID) would read back as the number 1, and 'yes' as true.
    return "'" + value.replace("'", "''") + "'"


def yaml_point(point):
    """Return an (x, y) point as a YAML flow list: [x, y]."""
    return '[' + ', '.join(yaml_float(v) for v in point) + ']'


def yaml_points(points):
    """Return a list of (x, y) points as a YAML flow list: [[x, y], [x, y], ...]."""
    return '[' + ', '.join(yaml_point(p) for p in points) + ']'


def yaml_names(names):
    """Return a list of names as a YAML flow list: [A01, B01]."""
    return '[' + ', '.join(yaml_str(name) for name in names) + ']'


def yaml_flow(pairs):
    """Return (key, formatted value) pairs as a YAML flow mapping: {key: value, ...}."""
    return '{' + ', '.join(f'{yaml_str(key)}: {value}' for key, value in pairs) + '}'
